# ==================== 23-24 招生类型映射 ====================
def map_2324_type(supp_type: Optional[str], fname: str) -> tuple[Optional[str], Optional[str]]:
    """23-24 征集招生类型 → (主表招生类型, 错误标记).

    优先使用 xlsx 的招生类型字段; 无则从文件名推断; 兜底 "普通类本科".
    """
    # 1. 如果 xlsx 有招生类型字段
    if supp_type:
        t = supp_type.strip()
        if t in SUPP_TYPE_2324:
            mtype = SUPP_TYPE_2324[t]
            # "普通类本科" 默认; 若 fname 含专科, 改为 普通类高职(专科)
            if mtype == "普通类本科" and ("专科" in fname or "高职" in fname):
                mtype = "普通类高职(专科)"
            return mtype, None
        # 逐字包含匹配
        for key, val in SUPP_TYPE_2324.items():
            if key in t:
                mtype = val
                if mtype == "普通类本科" and ("专科" in fname or "高职" in fname):
                    mtype = "普通类高职(专科)"
                return mtype, None

    # 2. 从文件名推断
    for keyword, mtype in FILENAME_TYPE_KEYWORDS:
        if keyword in fname:
            return mtype, None

    # 3. 兜底
    if "专科" in fname or "高职" in fname:
        return "普通类高职(专科)", None
    return "普通类本科", None
